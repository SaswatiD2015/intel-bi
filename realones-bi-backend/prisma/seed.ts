import { PrismaClient, Role, OrderStatus } from '@prisma/client';
import { hash } from 'argon2';

const prisma = new PrismaClient();

async function main() {
  console.log('Starting seed process...');

  // 1. Setup Roles and Users
  const passwordHash = await hash('Demo123!');

  const analyst = await prisma.user.upsert({
    where: { email: 'analyst@realonesbi.demo' },
    update: {},
    create: {
      email: 'analyst@realonesbi.demo',
      passwordHash,
      userRoles: { create: { role: Role.ANALYST } },
    },
  });

  const businessUser = await prisma.user.upsert({
    where: { email: 'business@realonesbi.demo' },
    update: {},
    create: {
      email: 'business@realonesbi.demo',
      passwordHash,
      userRoles: { create: { role: Role.BUSINESS_USER } },
    },
  });

  // 2. Setup Regions
  const regions = ['North', 'South', 'East', 'West'];
  const regionMap = new Map();
  for (const name of regions) {
    const region = await prisma.region.upsert({
      where: { name },
      update: {},
      create: { name },
    });
    regionMap.set(name, region.id);
  }

  // Assign Business User to South region only
  await prisma.userRegionAccess.upsert({
    where: { userId_regionId: { userId: businessUser.id, regionId: regionMap.get('South') } },
    update: {},
    create: { userId: businessUser.id, regionId: regionMap.get('South') },
  });

  // 3. Semantic Layer: Glossary and Metrics
  const glossaryTerms = [
    { term: 'Revenue', definition: 'The total amount of income generated by the sale of goods.' },
    { term: 'Completed Order', definition: 'An order that has been successfully delivered and paid.' },
  ];

  for (const g of glossaryTerms) {
    await prisma.businessGlossary.upsert({
      where: { term: g.term },
      update: {},
      create: g,
    });
  }

  const revenueMetric = await prisma.metricDefinition.upsert({
    where: { metricKey: 'completed_order_revenue' },
    update: {},
    create: {
      metricKey: 'completed_order_revenue',
      displayName: 'Completed-order revenue',
      description: 'Sum of item quantity multiplied by unit price for completed orders only.',
      formulaDescription: 'SUM(order_items.quantity * order_items.unit_price)',
      approvedSqlTemplate: 'SUM(oi.quantity * oi.unit_price)',
      sourceTables: ['orders', 'order_items'],
      requiredJoins: ['orders-order_items'],
      allowedDimensions: ['region', 'category', 'month'],
      allowedFilters: ['status', 'region'],
      grain: 'order_item',
      synonyms: ['sales', 'revenue', 'completed sales', 'order revenue'],
    },
  });

  // 4. Products and Categories
  const categories = ['Electronics', 'Clothing', 'Home', 'Toys', 'Sports', 'Books', 'Health', 'Beauty', 'Automotive', 'Garden'];
  const catMap = new Map();
  for (const c of categories) {
    const cat = await prisma.productCategory.upsert({
      where: { name: c },
      update: {},
      create: { name: c, description: `${c} Category` },
    });
    catMap.set(c, cat.id);
  }

  const productIds = [];
  for (let i = 1; i <= 50; i++) {
    const catName = categories[i % 10];
    const product = await prisma.product.create({
      data: {
        name: `Product ${i}`,
        categoryId: catMap.get(catName),
        unitCost: (Math.random() * 50 + 5).toFixed(2),
      },
    });
    productIds.push(product.id);
  }

  // 5. Customers
  console.log('Seeding Customers...');
  const customerIds = [];
  for (let i = 1; i <= 1000; i++) {
    const customer = await prisma.customer.create({
      data: {
        name: `Customer ${i}`,
        email: `customer${i}@example.com`,
        segment: i % 3 === 0 ? 'Enterprise' : 'SMB',
      },
    });
    customerIds.push(customer.id);
  }

  // 6. Orders (5000 orders)
  console.log('Seeding 5,000 Orders... This might take a moment.');
  const orderStatuses = [OrderStatus.COMPLETED, OrderStatus.COMPLETED, OrderStatus.COMPLETED, OrderStatus.PENDING, OrderStatus.CANCELLED, OrderStatus.RETURNED];
  
  const orderBatch = [];
  const orderItemBatch = [];

  // Define date range: Last 24 months
  const now = new Date();
  const twoYearsAgo = new Date();
  twoYearsAgo.setMonth(now.getMonth() - 24);

  // We will insert sequentially in smaller chunks to avoid memory/timeout issues
  const chunkSize = 500;
  for (let c = 0; c < 5000 / chunkSize; c++) {
    for (let i = 0; i < chunkSize; i++) {
      const randomDate = new Date(twoYearsAgo.getTime() + Math.random() * (now.getTime() - twoYearsAgo.getTime()));
      
      const order = await prisma.order.create({
        data: {
          customerId: customerIds[Math.floor(Math.random() * customerIds.length)],
          regionId: regionMap.get(regions[Math.floor(Math.random() * regions.length)]),
          orderDate: randomDate,
          status: orderStatuses[Math.floor(Math.random() * orderStatuses.length)],
        },
      });

      // Add 1 to 3 items per order
      const numItems = Math.floor(Math.random() * 3) + 1;
      for (let j = 0; j < numItems; j++) {
        await prisma.orderItem.create({
          data: {
            orderId: order.id,
            productId: productIds[Math.floor(Math.random() * productIds.length)],
            quantity: Math.floor(Math.random() * 5) + 1,
            unitPrice: (Math.random() * 100 + 10).toFixed(2),
          },
        });
      }
    }
    console.log(`Seeded ${ (c + 1) * chunkSize } orders...`);
  }

  console.log('Seed process completed successfully.');
}

main()
  .catch((e) => {
    console.error('Seed Error:', e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
